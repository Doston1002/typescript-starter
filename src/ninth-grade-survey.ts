const makeQuestions = (
  prompts: string[],
  answers: [string, string],
): SurveyQuestion[] =>
  prompts.map((prompt, index) => ({
    prompt: `${index + 1}. ${prompt}`,
    type: 'choice',
    options: answers,
  }));

