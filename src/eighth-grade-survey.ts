const makeQuestions = (
  prompts: string[],
  answers: [string, string],
  headings: string[],
): SurveyQuestion[] =>
  prompts.map((prompt, index) => {
    const sectionIndex = Math.floor(index / 9);
    const sectionPrompt = index % 9 === 0 ? `${headings[sectionIndex]}\n` : '';
    return {
      prompt: `${sectionPrompt}${index + 1}. ${prompt}`,
      type: 'choice',
      options: answers,
    };
  });

export const eighthGradeSurvey: Record<'uz' | 'ru', SurveyQuestion[]> = {
  uz: makeQuestions(uzQuestions, ['Ha', 'Yo‘q'], sectionHeadings.uz),
  ru: makeQuestions(ruQuestions, ['Да', 'Нет'], sectionHeadings.ru),
};
